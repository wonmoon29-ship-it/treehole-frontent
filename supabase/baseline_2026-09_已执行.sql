CREATE TABLE public.authors (
    token UUID PRIMARY KEY,
    display_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE public.posts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    author_token UUID REFERENCES public.authors(token) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    is_hidden BOOLEAN DEFAULT FALSE
);

CREATE TABLE public.replies (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    post_id UUID REFERENCES public.posts(id) ON DELETE CASCADE NOT NULL,
    author_token UUID REFERENCES public.authors(token) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    is_hidden BOOLEAN DEFAULT FALSE
);

ALTER TABLE public.authors ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.replies ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow anonymous insert authors" ON public.authors FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow anonymous read authors" ON public.authors FOR SELECT USING (true);

CREATE POLICY "Allow anonymous insert posts" ON public.posts FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow anonymous read posts" ON public.posts FOR SELECT USING (is_hidden = false);

CREATE POLICY "Allow anonymous insert replies" ON public.replies FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow anonymous read replies" ON public.replies FOR SELECT USING (is_hidden = false);

GRANT SELECT, INSERT ON public.authors TO anon;
GRANT SELECT, INSERT ON public.posts TO anon;
GRANT SELECT, INSERT ON public.replies TO anon;
GRANT SELECT, INSERT ON public.authors TO authenticated;
GRANT SELECT, INSERT ON public.posts TO authenticated;
GRANT SELECT, INSERT ON public.replies TO authenticated;

